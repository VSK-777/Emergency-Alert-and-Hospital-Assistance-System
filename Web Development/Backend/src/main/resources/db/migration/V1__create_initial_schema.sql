-- =============================================================================
-- Migration V1: Initial PostgreSQL / ANSI Schema
-- Emergency Alert and Hospital Assistance System
-- VVIT Community Service Project (CSP)
-- =============================================================================

-- 1. Users Table
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(150) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'CITIZEN',
    blood_group VARCHAR(10),
    allergies TEXT,
    medical_conditions TEXT,
    medications TEXT,
    is_active BOOLEAN DEFAULT TRUE,
    hospital_id BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 2. Hospitals Table
CREATE TABLE IF NOT EXISTS hospitals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    address TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    emergency_capacity INTEGER DEFAULT 20,
    available_icus INTEGER DEFAULT 5,
    available_ambulances INTEGER DEFAULT 3,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. Responders Table
CREATE TABLE IF NOT EXISTS responders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    specialization VARCHAR(100) NOT NULL,
    organization VARCHAR(120) DEFAULT 'VVIT NSS Unit',
    verification_status VARCHAR(30) DEFAULT 'VERIFIED',
    certificate_details TEXT,
    skills TEXT,
    is_available BOOLEAN DEFAULT TRUE,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    last_active_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 4. User Devices Table
CREATE TABLE IF NOT EXISTS user_devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    device_type VARCHAR(30) NOT NULL,
    device_identifier VARCHAR(100) NOT NULL,
    fcm_token VARCHAR(255),
    is_active BOOLEAN DEFAULT TRUE,
    last_synced_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 5. Emergency Contacts Table
CREATE TABLE IF NOT EXISTS emergency_contacts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    relationship VARCHAR(50) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    is_primary BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 6. Emergency Incidents Table
CREATE TABLE IF NOT EXISTS emergency_incidents (
    id VARCHAR(64) PRIMARY KEY,
    user_id BIGINT,
    source VARCHAR(40) NOT NULL DEFAULT 'MOBILE_SOS',
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    accuracy_meters DOUBLE PRECISION,
    location_timestamp TIMESTAMP,
    detection_reason VARCHAR(255),
    detection_score DOUBLE PRECISION,
    assigned_hospital_id BIGINT,
    assigned_responder_id BIGINT,
    hospital_acknowledgement VARCHAR(30) DEFAULT 'PENDING',
    hospital_decline_reason TEXT,
    hospital_preparation_status VARCHAR(40) DEFAULT 'NOT_STARTED',
    responder_acceptance_status VARCHAR(30) DEFAULT 'NOT_ASSIGNED',
    internal_notes TEXT,
    assigned_ambulance_id BIGINT,
    assigned_ambulance_plate VARCHAR(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP
);

-- 7. Ambulances Table
CREATE TABLE IF NOT EXISTS ambulances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_number VARCHAR(30) NOT NULL UNIQUE,
    hospital_id BIGINT,
    vehicle_type VARCHAR(50) NOT NULL,
    driver_name VARCHAR(100) NOT NULL,
    driver_phone VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    equipment TEXT,
    assigned_incident_id VARCHAR(64),
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 8. Detection Events Table
CREATE TABLE IF NOT EXISTS detection_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    acceleration_magnitude DOUBLE PRECISION,
    angular_velocity DOUBLE PRECISION,
    post_impact_inactivity_sec INTEGER,
    raw_telemetry_json TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 9. Notification Attempts Table
CREATE TABLE IF NOT EXISTS notification_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id VARCHAR(64) NOT NULL,
    recipient_type VARCHAR(30) NOT NULL,
    recipient_id VARCHAR(100) NOT NULL,
    channel VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    message_payload TEXT,
    attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 10. Medical Expenses Table
CREATE TABLE IF NOT EXISTS medical_expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id VARCHAR(64) NOT NULL,
    user_id BIGINT NOT NULL,
    category VARCHAR(50) NOT NULL,
    description VARCHAR(255) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 11. Synchronization Records Table
CREATE TABLE IF NOT EXISTS synchronization_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    incident_id VARCHAR(64) NOT NULL,
    device_id VARCHAR(100),
    sync_status VARCHAR(30) NOT NULL,
    payload_hash VARCHAR(128),
    synced_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 12. Audit Logs Table
CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(80) NOT NULL,
    actor_email VARCHAR(120),
    actor_role VARCHAR(50),
    incident_id VARCHAR(64),
    details TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
