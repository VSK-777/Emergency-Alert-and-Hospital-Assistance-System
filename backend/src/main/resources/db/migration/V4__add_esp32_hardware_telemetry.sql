CREATE TABLE IF NOT EXISTS hardware_telemetry_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_identifier VARCHAR(100) NOT NULL,
    heart_rate INTEGER,
    spo2 INTEGER,
    signal_quality INTEGER,
    accel_x DOUBLE PRECISION,
    accel_y DOUBLE PRECISION,
    accel_z DOUBLE PRECISION,
    accel_magnitude DOUBLE PRECISION,
    device_state VARCHAR(50) NOT NULL,
    operating_mode VARCHAR(20) NOT NULL,
    countdown_sec INTEGER DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_telemetry_device_time ON hardware_telemetry_logs (device_identifier, created_at DESC);
