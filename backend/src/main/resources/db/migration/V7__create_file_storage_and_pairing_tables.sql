-- 1. Device Pairing Challenges Table
CREATE TABLE IF NOT EXISTS device_pairing_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    challenge_code VARCHAR(64) NOT NULL UNIQUE,
    claim_secret VARCHAR(64) NOT NULL,
    device_type VARCHAR(30) NOT NULL,
    is_consumed BOOLEAN DEFAULT FALSE,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_pairing_challenges_code ON device_pairing_challenges (challenge_code, expires_at);
CREATE INDEX IF NOT EXISTS idx_pairing_challenges_user ON device_pairing_challenges (user_id);

-- 2. Medical Documents & Incident File Attachments Table (Supabase S3 Storage Metadata)
CREATE TABLE IF NOT EXISTS medical_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    incident_id VARCHAR(64) REFERENCES emergency_incidents(id) ON DELETE SET NULL,
    file_name VARCHAR(255) NOT NULL,
    file_type VARCHAR(100) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    storage_key VARCHAR(500) NOT NULL UNIQUE,
    bucket_name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    upload_status VARCHAR(30) NOT NULL DEFAULT 'CONFIRMED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_med_docs_user ON medical_documents (user_id);
CREATE INDEX IF NOT EXISTS idx_med_docs_incident ON medical_documents (incident_id);

-- 3. Enhance user_devices table with pairing status and firmware tracking
ALTER TABLE user_devices
    ADD COLUMN IF NOT EXISTS pairing_status VARCHAR(30) DEFAULT 'PAIRED',
    ADD COLUMN IF NOT EXISTS firmware_version VARCHAR(50) DEFAULT 'CSP-Triage-V1';

CREATE INDEX IF NOT EXISTS idx_devices_active_user ON user_devices (user_id, is_active);
